# Arrithematic operators

a = 10
b = 4

print(a+b) # add
print(a-b) #subtract
print(a*b) #multiply
print(a/b) #division
print(a**b) #exponent
print(a//b) #floor division
print(a%b) #remainder

# Comparision Operator ; always return value in boolean 

x = 5
y = 7
 
print(x==y) # false 
print(x!=y) #true
print(x<y)  #true
print(x>y)  #false
print(x<=y) #true
print(x>=y) #false
